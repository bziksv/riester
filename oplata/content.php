<h1>Условия оплаты интернет-магазина riester.su</h1>
<p>
 <b>Услуги предоставляются физическим и юридическим лицам по полной предоплате.</b><br>
 <br>
	 Заказчику выставляется безналичный счет. За товар следует заплатить 100% стоимости. По приходу денег на расчетный счет компании, заказ передается в доставку.<br>
 <br>
	 Мы уже более 7 лет на рынке медицинской продукции. Система обслуживания клиентов на высшем уровне. Вы обязательно получите коммерческое предложение, которое удовлетворит все ваши потребности, а товар будет доставлен очень быстро.<br>
 <br>
	 Если вам что-то не понравится в работе со специалистами, директор лично ответит на все вопросы и выполнит ваши индивидуальные пожелания. Для этого отправьте ему письмо на личную почту <a href="mailto:director@riester.su">director@riester.su</a><br>
